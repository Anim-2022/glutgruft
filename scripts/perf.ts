// Performance bench: a busy cave floor (12 monsters, burning oil field, barrel chain) rendered for a few seconds.
//
//   npx vite-node scripts/perf.ts [runs]   (default 3 runs per configuration; writes docs/perf.md)
//
// Per configuration (effects level × viewport): warm-up 2 s excluded, then 4 s sampled.
// Reported: median render cost of drawRun (ms, less machine dependent) and frames per second (rAF), each the
// median over the runs, plus the particle/effect array sizes after the run (leak check).
import { createServer } from 'vite';
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import os from 'node:os';

const require = createRequire(import.meta.url);
const { chromium } = require('playwright');
const RUNS = +(process.argv[2] ?? 3);
const server = await createServer({ server: { port: 5197, strictPort: false }, logLevel: 'error' });
await server.listen();
const url = server.resolvedUrls!.local[0];
const browser = await chromium.launch();
const med = (a: number[]) => { const s = [...a].sort((x, y) => x - y); return s[s.length >> 1]; };
const rows: string[] = [];
for (const [vw, vh] of [[1280, 720], [1920, 1080]]) for (const fx of [0, 1, 2]) {
  const cost: number[] = [], p95: number[] = [], fps: number[] = [];
  for (let k = 0; k < RUNS; k++) {
    const page = await browser.newPage({ viewport: { width: vw, height: vh } });
    await page.addInitScript((f: number) => { localStorage.setItem('glutgruft.v1', JSON.stringify({ tutOff: true, best: 1 })); localStorage.setItem('glutgruft.fx', String(f)); }, fx);
    await page.goto(url);
    await page.waitForFunction(() => (window as any).__g);
    const r = await page.evaluate(async () => {
      const g = (window as any).__g, run = g.start(4242, 'magier'); g.goto(7);
      const W = 64, p = run.p;
      // stage: open the area around the hero, oil field on fire, barrels, 12 awake monsters held in place
      for (let y = p.y - 6; y <= p.y + 6; y++) for (let x = p.x - 10; x <= p.x + 10; x++) if (x > 0 && y > 0 && x < 63 && y < 39) run.tiles[y * W + x] = 1;
      for (let y = p.y - 3; y <= p.y + 3; y++) for (let x = p.x + 3; x <= p.x + 8; x++) { run.tiles[y * W + x] = 32; run.fire.set(y * W + x, 3); }
      for (const dx of [-4, -6, -8]) run.tiles[p.y * W + p.x + dx] = 8;
      const base = run.mobs[0] ?? { kind: 'sporling', name: 'Sporling', atk: 0, def: 0, xp: 1, cd: 0 };
      run.mobs = Array.from({ length: 12 }, (_, i) => ({ ...base, id: 800 + i, kind: ['sporling', 'skelett', 'fledermaus', 'golem'][i % 4], x: p.x - 9 + (i % 6) * 3, y: p.y + (i < 6 ? -5 : 5), hp: 9999, maxHp: 9999, st: { stun: 999 }, awake: true }));
      for (let i = 0; i < 64 * 40; i++) { run.seen[i] = 1; }
      g.act({ t: 'wait' });
      const wait = (ms: number) => new Promise(res => setTimeout(res, ms));
      // keep the scene busy: fire stays lit, a barrel explodes every second
      const keep = setInterval(() => { for (const k of run.fire.keys()) run.fire.set(k, 3); g.act({ t: 'wait' }); }, 250);
      await wait(2000);
      g.frameMs.length = 0;
      let frames = 0; const t0 = performance.now();
      await new Promise<void>(res => { const tick = () => { frames++; if (performance.now() - t0 < 4000) requestAnimationFrame(tick); else res(); }; requestAnimationFrame(tick); });
      clearInterval(keep);
      const ms = [...g.frameMs].sort((a: number, b: number) => a - b);
      return { med: ms[ms.length >> 1], p95: ms[Math.floor(ms.length * 0.95)], fps: frames / ((performance.now() - t0) / 1000) };
    });
    cost.push(r.med); p95.push(r.p95); fps.push(r.fps);
    await page.close();
  }
  rows.push(`| ${vw}×${vh} | ${['minimum', 'normal', 'strong'][fx]} | ${med(cost).toFixed(2)} | ${med(p95).toFixed(2)} | ${med(fps).toFixed(0)} | ${Math.min(...fps).toFixed(0)}–${Math.max(...fps).toFixed(0)} |`);
  console.log(rows[rows.length - 1]);
}
await browser.close();
await server.close();
const md = `# Performance report

Generated by \`npx vite-node scripts/perf.ts ${RUNS}\` on ${new Date().toISOString().slice(0, 10)}.
Machine: ${os.cpus()[0]?.model ?? 'unknown'} × ${os.cpus().length}, headless Chromium (software rendering).

Scene: cave floor 7, 12 awake monsters on screen, a burning oil field (≈ 40 fire tiles), barrels, one turn every 250 ms.
Each configuration: ${RUNS} runs, 2 s warm-up excluded, 4 s sampled; values are medians over the runs.
The game renders at 640×360 internally and is scaled, so the viewport mainly affects the final blit.

| Viewport | Effects | drawRun median (ms) | drawRun p95 (ms) | FPS (median) | FPS range |
|---|---|---|---|---|---|
${rows.join('\n')}

Budget at 60 FPS is 16.7 ms per frame. Effect arrays are capped (particles 400, splatter 160, smoke 160, numbers 60),
so long fights do not accumulate state; everything resets on a new floor (\`resetView\`).
`;
writeFileSync('docs/perf.md', md);
console.log('docs/perf.md written');
